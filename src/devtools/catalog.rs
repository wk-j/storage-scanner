//! Tools whose caches, stores and downloads the developer tab measures, with the command that
//! cleans each. Paths starting `~/` are in the home folder; the rest are system paths.

use super::Group;

pub(super) enum Cmd {
    /// A tool's own cleanup command.
    Run(&'static str),
    /// `rm -rf` of the paths that exist.
    Remove,
}

